#!/usr/bin/env python3
"""Generate the file://-compatible gallery catalog from canonical catalog.json."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1] / 'assets' / 'scene-patterns'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
patterns = json.loads((root / 'catalog.json').read_text())['patterns']
ids = [p['id'] for p in patterns]
if len(ids) != len(set(ids)):
    raise SystemExit('Duplicate pattern IDs')
output = '// Generated by scripts/build_scene_catalog.py; edit catalog.json.\n'
output += 'window.SCENE_CATALOG = ' + json.dumps(patterns, ensure_ascii=False, indent=2) + ';\n'
target = root / 'catalog.js'
if args.check:
    if target.read_text() != output:
        raise SystemExit('Stale catalog.js; run build_scene_catalog.py')
    print(f'{len(ids)} pattern records; generated catalog is current')
else:
    target.write_text(output)
