#!/usr/bin/env python3
"""Generate the file://-compatible gallery catalog from canonical catalog.json."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1] / 'assets' / 'scene-patterns'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
catalog = json.loads((root / 'catalog.json').read_text())
patterns = catalog['patterns']
ids = [p['id'] for p in patterns]
if len(ids) != len(set(ids)):
    raise SystemExit('Duplicate pattern IDs')
output = '// Generated by scripts/build_scene_catalog.py; edit catalog.json.\n'
output += 'window.SCENE_LIBRARY = ' + json.dumps(catalog, ensure_ascii=False, indent=2) + ';\n'
output += 'window.SCENE_CATALOG = window.SCENE_LIBRARY.patterns;\n'
outputs = {root / 'catalog.js': output}
layouts = {p['id']: (root / 'layouts' / (p['id'] + '.html')).read_text() for p in patterns}
outputs[root / 'layouts.js'] = '// Generated by scripts/build_scene_catalog.py; edit layouts/*.html.\nwindow.SCENE_LAYOUTS = ' + json.dumps(layouts, ensure_ascii=False, indent=2) + ';\n'
for target, content in outputs.items():
    if args.check:
        if not target.exists() or target.read_text() != content:
            raise SystemExit(f'Stale {target.name}; run build_scene_catalog.py')
    else:
        target.write_text(content)
if args.check:
    print(f'{len(ids)} catalog records and layouts are current')
